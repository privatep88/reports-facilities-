import fs from 'fs';
import path from 'path';

const BASE_PATH = '/reports-facilities-/';

/**
 * Generates a valid binary 16x16 32-bit ICO file (SAAED Navy #142A45 & Gold #D4A447)
 * so browsers requesting /reports-facilities-/favicon.ico or /favicon.ico get HTTP 200 image/x-icon.
 */
function createFaviconIcoBuffer() {
  const width = 16;
  const height = 16;
  const pixelDataSize = width * height * 4;
  const andMaskSize = ((width + 31) >> 5) * 4 * height; // 64 bytes
  const dibHeaderSize = 40;
  const imageSize = dibHeaderSize + pixelDataSize + andMaskSize;
  const icoHeaderSize = 6;
  const dirEntrySize = 16;
  const totalSize = icoHeaderSize + dirEntrySize + imageSize;

  const buf = Buffer.alloc(totalSize, 0);

  // ICO Header
  buf.writeUInt16LE(0, 0); // Reserved
  buf.writeUInt16LE(1, 2); // Type: 1 = ICO
  buf.writeUInt16LE(1, 4); // Image count: 1

  // Directory Entry
  buf.writeUInt8(width, 6);
  buf.writeUInt8(height, 7);
  buf.writeUInt8(0, 8); // Palette count
  buf.writeUInt8(0, 9); // Reserved
  buf.writeUInt16LE(1, 10); // Color planes
  buf.writeUInt16LE(32, 12); // Bits per pixel
  buf.writeUInt32LE(imageSize, 14);
  buf.writeUInt32LE(icoHeaderSize + dirEntrySize, 18);

  // BITMAPINFOHEADER (40 bytes)
  const dibOffset = icoHeaderSize + dirEntrySize;
  buf.writeUInt32LE(dibHeaderSize, dibOffset);
  buf.writeInt32LE(width, dibOffset + 4);
  buf.writeInt32LE(height * 2, dibOffset + 8); // XOR + AND height
  buf.writeUInt16LE(1, dibOffset + 12); // Planes
  buf.writeUInt16LE(32, dibOffset + 14); // BitCount
  buf.writeUInt32LE(0, dibOffset + 16); // Compression BI_RGB
  buf.writeUInt32LE(pixelDataSize + andMaskSize, dibOffset + 20);

  // Pixel data (bottom-up BGRA)
  const pixelOffset = dibOffset + dibHeaderSize;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = pixelOffset + (y * width + x) * 4;
      // Diamond Manhattan distance from center (7.5, 7.5)
      const dist = Math.abs(x - 7.5) + Math.abs(y - 7.5);
      const isGap = Math.abs(x - 7.5) < 1.0 || Math.abs(y - 7.5) < 1.0;
      if (dist <= 5.5 && !isGap) {
        // SAAED Gold (#D4A447 -> BGRA: 0x47, 0xA4, 0xD4, 0xFF)
        buf[idx] = 0x47;
        buf[idx + 1] = 0xa4;
        buf[idx + 2] = 0xd4;
        buf[idx + 3] = 0xff;
      } else {
        // SAAED Navy (#142A45 -> BGRA: 0x45, 0x2A, 0x14, 0xFF)
        buf[idx] = 0x45;
        buf[idx + 1] = 0x2a;
        buf[idx + 2] = 0x14;
        buf[idx + 3] = 0xff;
      }
    }
  }

  return buf;
}

function runPostBuildAndVerify() {
  console.log('--- Starting Post-Build & GitHub Pages Verification ---');

  // 1. Ensure public/favicon.ico exists
  fs.mkdirSync('public', { recursive: true });
  const icoBuffer = createFaviconIcoBuffer();
  fs.writeFileSync(path.join('public', 'favicon.ico'), icoBuffer);

  // 2. Verify dist directory was created by Vite
  if (!fs.existsSync('dist') || !fs.existsSync('dist/index.html')) {
    console.error('FATAL: dist/index.html was not generated by vite build.');
    process.exit(1);
  }

  // 3. Copy favicon files into dist/, dist/assets/, root ./, and ./assets/
  fs.mkdirSync(path.join('dist', 'assets'), { recursive: true });
  fs.writeFileSync(path.join('dist', 'favicon.ico'), icoBuffer);
  fs.writeFileSync(path.join('dist', 'assets', 'favicon.ico'), icoBuffer);
  fs.writeFileSync('favicon.ico', icoBuffer);
  if (fs.existsSync(path.join('public', 'favicon.svg'))) {
    fs.copyFileSync(path.join('public', 'favicon.svg'), path.join('dist', 'favicon.svg'));
    fs.copyFileSync(path.join('public', 'favicon.svg'), path.join('dist', 'assets', 'favicon.svg'));
    fs.copyFileSync(path.join('public', 'favicon.svg'), 'favicon.svg');
  }

  // 4. Write compatibility shims for any cached legacy hashed bundle URLs
  const legacyJsShims = ['index-B2qv8KGN.js', 'index-DNysLAl3.js'];
  const legacyCssShims = ['index-aTwR7x5y.css', 'index-D9Zh6moI.css'];
  for (const jsFile of legacyJsShims) {
    fs.writeFileSync(path.join('dist', 'assets', jsFile), 'import "./index.js";\n');
  }
  for (const cssFile of legacyCssShims) {
    fs.writeFileSync(path.join('dist', 'assets', cssFile), '@import "./index.css";\n');
  }

  // 5. Create dist/404.html and dist/.nojekyll for GitHub Actions Pages artifact
  fs.copyFileSync(path.join('dist', 'index.html'), path.join('dist', '404.html'));
  fs.writeFileSync(path.join('dist', '.nojekyll'), '');

  // 6. Sync dist/ outputs to repository root (./index.html, ./404.html, ./assets/, ./.nojekyll)
  // so GitHub Pages works seamlessly whether configured for GitHub Actions OR Branch (root) deployment
  fs.mkdirSync('assets', { recursive: true });
  for (const file of fs.readdirSync(path.join('dist', 'assets'))) {
    fs.copyFileSync(path.join('dist', 'assets', file), path.join('assets', file));
  }
  fs.copyFileSync(path.join('dist', 'index.html'), 'index.html');
  fs.copyFileSync(path.join('dist', 'index.html'), '404.html');
  fs.writeFileSync('.nojekyll', '');

  // 7. Strict Verification Checks
  const distHtml = fs.readFileSync(path.join('dist', 'index.html'), 'utf-8');
  const rootHtml = fs.readFileSync('index.html', 'utf-8');

  // Check A: Ensure no raw TypeScript / TSX references exist in built HTML
  if (distHtml.includes('/src/main.tsx') || distHtml.includes('.tsx') || rootHtml.includes('/src/main.tsx')) {
    console.error('FATAL: Built index.html still references raw TypeScript source (/src/main.tsx)!');
    process.exit(1);
  }

  // Check B: Ensure compiled entry JS and CSS are referenced with correct base path
  if (!distHtml.includes(`${BASE_PATH}assets/index.js`)) {
    console.error(`FATAL: dist/index.html does not reference ${BASE_PATH}assets/index.js`);
    process.exit(1);
  }
  if (!distHtml.includes(`${BASE_PATH}assets/index.css`)) {
    console.error(`FATAL: dist/index.html does not reference ${BASE_PATH}assets/index.css`);
    process.exit(1);
  }

  // Check C: Verify every asset referenced in dist/index.html physically exists in dist/ and root ./
  const assetRefs = [...distHtml.matchAll(/(?:src|href)="([^"]+)"/g)].map(m => m[1]);
  for (const ref of assetRefs) {
    if (ref.startsWith(BASE_PATH)) {
      const relPath = ref.slice(BASE_PATH.length);
      const distTarget = path.join('dist', relPath);
      const rootTarget = path.join('.', relPath);
      if (!fs.existsSync(distTarget)) {
        console.error(`FATAL: Referenced asset missing in dist/: ${distTarget} (from ${ref})`);
        process.exit(1);
      }
      if (!fs.existsSync(rootTarget)) {
        console.error(`FATAL: Referenced asset missing in root ./: ${rootTarget} (from ${ref})`);
        process.exit(1);
      }
    }
  }

  // Check D: Verify all required image bundles exist in dist/assets/ and ./assets/
  const distAssets = fs.readdirSync(path.join('dist', 'assets'));
  const imageAssets = distAssets.filter(f => /\.(jpg|jpeg|png|svg|webp)$/i.test(f));
  if (imageAssets.length < 6) {
    console.error(`FATAL: Expected at least 6 bundled image assets in dist/assets/, found ${imageAssets.length}`);
    process.exit(1);
  }

  console.log('✓ Verified: No /src/main.tsx or raw .tsx references in production HTML.');
  console.log(`✓ Verified: Base path "${BASE_PATH}" applied to all JS, CSS, and Favicon tags.`);
  console.log(`✓ Verified: ${distAssets.length} production assets in dist/assets/ and ./assets/ (${imageAssets.length} images).`);
  console.log('✓ Verified: favicon.ico and favicon.svg generated and present in public/, dist/, and root.');
  console.log('--- Post-Build Verification Succeeded ---');
}

runPostBuildAndVerify();
